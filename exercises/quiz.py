#!/usr/bin/env python3
"""Open Engineering Playbook true-or-false quiz.

Shows one statement at a time. Decide whether it is true or false. After each
answer you see whether you were right, why, and which page teaches it. At the
end you get a score by area and the three pages worth reading next.

Usage:
  python3 exercises/quiz.py [--area AREA ...] [--level LEVEL] [--count N] [--seed S]
  python3 exercises/quiz.py --list
  python3 exercises/quiz.py --export [DIR]
  python3 exercises/quiz.py --check

Answer with t, true, y or yes for true, and f, false, n or no for false.
Type q to stop early; you still get your score.

Exit codes:
  0  quiz finished, pages exported, or check passed
  1  --check found a problem
  2  the question bank or the arguments are invalid

Standard library only. Python 3.11 or later (uses tomllib).
"""
from __future__ import annotations

import argparse
import difflib
import random
import re
import sys
import textwrap
from collections import Counter
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Callable, TextIO

try:
    import tomllib
except ModuleNotFoundError:  # pragma: no cover
    sys.exit("quiz.py needs Python 3.11 or later (tomllib).")

LEVELS = ("foundation", "standard", "assured")
LEVEL_LABEL = {"foundation": "Foundation", "standard": "Standard", "assured": "Assured"}

SLUG = r"[a-z0-9]+(?:-[a-z0-9]+)*"
ID_RE = re.compile(rf"^{SLUG}\.{SLUG}$")
AREA_RE = re.compile(rf"^{SLUG}$")
# A sentence ends with . ! or ? (optionally followed by a closing quote or
# bracket) and then whitespace or the end of the text. "99.9%" does not count.
SENTENCE_END = re.compile(r"[.!?]['\")]?(?=\s|$)")
MIN_SENTENCES, MAX_SENTENCES = 2, 4

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
DEFAULT_BANK = HERE / "true-or-false" / "questions.toml"
DEFAULT_EXPORT = HERE / "true-or-false"
DEFAULT_COUNT = 10
NEXT_PAGES = 3
WIDTH = 78

TRUE_WORDS = {"t", "true", "y", "yes"}
FALSE_WORDS = {"f", "false", "n", "no"}
QUIT_WORDS = {"q", "quit", "exit"}
QUIT = "quit"

MARKER = "<!-- Generated by exercises/quiz.py --export from questions.toml. Edit the bank, not this page. -->"
INDEX_NAME = "README.md"


class QuizError(Exception):
    """Invalid input. The message is shown to the user as is."""


@dataclass(frozen=True)
class Area:
    id: str
    title: str
    intro: str
    index: int


@dataclass(frozen=True)
class Statement:
    id: str
    area: str
    level: str
    text: str
    answer: bool
    explanation: str
    link: str
    index: int


@dataclass(frozen=True)
class Bank:
    areas: tuple[Area, ...]
    statements: tuple[Statement, ...]

    def area(self, area_id: str) -> Area:
        for a in self.areas:
            if a.id == area_id:
                return a
        raise QuizError(f"unknown area {area_id!r}")

    def in_area(self, area_id: str) -> list[Statement]:
        return [s for s in self.statements if s.area == area_id]


@dataclass(frozen=True)
class Result:
    statement: Statement
    reply: bool

    @property
    def correct(self) -> bool:
        return self.reply == self.statement.answer


# ------------------------------------------------------------------ loading


def count_sentences(text: str) -> int:
    return len(SENTENCE_END.findall(text.strip()))


def _text(raw: dict[str, Any], field: str) -> str:
    value = raw.get(field)
    return value.strip() if isinstance(value, str) else ""


def parse_bank(data: dict[str, Any]) -> Bank:
    errors: list[str] = []
    areas: list[Area] = []
    seen_areas: set[str] = set()
    for i, raw in enumerate(data.get("areas", [])):
        area_id = raw.get("id", "")
        if not isinstance(area_id, str) or not AREA_RE.match(area_id):
            errors.append(f"areas[{i}]: id {area_id!r} must be lower case words joined by hyphens")
            continue
        if area_id in seen_areas:
            errors.append(f"areas[{i}]: duplicate area id {area_id!r}")
            continue
        seen_areas.add(area_id)
        for field in ("title", "intro"):
            if not _text(raw, field):
                errors.append(f"areas[{i}] ({area_id}): missing {field}")
        areas.append(Area(area_id, _text(raw, "title") or area_id, _text(raw, "intro"), len(areas)))

    statements: list[Statement] = []
    seen_ids: set[str] = set()
    for i, raw in enumerate(data.get("statements", [])):
        sid = raw.get("id", "")
        where = f"statements[{i}] ({sid or 'no id'})"
        if not isinstance(sid, str) or not ID_RE.match(sid):
            errors.append(f"{where}: id must look like 'area.short-name'")
            continue
        if sid in seen_ids:
            errors.append(f"{where}: duplicate statement id")
            continue
        seen_ids.add(sid)
        prefix = sid.split(".", 1)[0]
        area_id = raw.get("area", "")
        if area_id != prefix:
            errors.append(f"{where}: area {area_id!r} must match the id prefix {prefix!r}")
        elif area_id not in seen_areas:
            errors.append(f"{where}: area {area_id!r} is not listed under [[areas]]")
        level = raw.get("level", "")
        if level not in LEVELS:
            errors.append(f"{where}: level must be one of {', '.join(LEVELS)}")
        answer = raw.get("answer")
        if not isinstance(answer, bool):
            errors.append(f"{where}: answer must be true or false, not {answer!r}")
        for field in ("statement", "explanation", "link"):
            if not _text(raw, field):
                errors.append(f"{where}: missing {field}")
        explanation = _text(raw, "explanation")
        if explanation:
            n = count_sentences(explanation)
            if not MIN_SENTENCES <= n <= MAX_SENTENCES:
                errors.append(
                    f"{where}: explanation has {n} sentence(s); write {MIN_SENTENCES} to {MAX_SENTENCES}"
                )
        link = _text(raw, "link")
        if link and (link.startswith("/") or "://" in link or not link.endswith(".md")):
            errors.append(f"{where}: link must be a relative path to a .md page, from the repository root")
        statements.append(
            Statement(
                id=sid,
                area=prefix,
                level=level,
                text=_text(raw, "statement"),
                answer=bool(answer),
                explanation=explanation,
                link=link,
                index=len(statements),
            )
        )

    for area in areas:
        if not any(s.area == area.id for s in statements):
            errors.append(f"area {area.id!r} has no statements")
    if not areas:
        errors.append("no [[areas]] defined")
    if errors:
        raise QuizError("Invalid question bank:\n  " + "\n  ".join(errors))
    return Bank(tuple(areas), tuple(statements))


def load_bank(path: Path) -> Bank:
    try:
        with path.open("rb") as fh:
            data = tomllib.load(fh)
    except FileNotFoundError:
        raise QuizError(f"question bank not found: {path}") from None
    except tomllib.TOMLDecodeError as exc:
        raise QuizError(f"question bank {path} is not valid TOML: {exc}") from None
    return parse_bank(data)


# ---------------------------------------------------------------- selecting


def select(
    bank: Bank,
    areas: list[str] | None = None,
    level: str | None = None,
    count: int = DEFAULT_COUNT,
    seed: int | None = None,
) -> list[Statement]:
    """Filter by area and level, shuffle, and keep `count` (0 keeps all)."""
    known = [a.id for a in bank.areas]
    for area_id in areas or []:
        if area_id not in known:
            hint = difflib.get_close_matches(area_id, known, n=1)
            suffix = f" (did you mean {hint[0]!r}?)" if hint else ""
            raise QuizError(f"unknown area {area_id!r}{suffix}; run --list to see them all")
    if level is not None and level not in LEVELS:
        raise QuizError(f"unknown level {level!r}; use one of {', '.join(LEVELS)}")
    if count < 0:
        raise QuizError("--count must be 0 (all) or more")

    chosen = [
        s
        for s in bank.statements
        if (not areas or s.area in areas) and (level is None or s.level == level)
    ]
    if not chosen:
        raise QuizError("no statements match that area and level")
    random.Random(seed).shuffle(chosen)
    return chosen[:count] if count else chosen


# ------------------------------------------------------------------ scoring


def parse_reply(text: str) -> bool | str | None:
    """True, False, QUIT, or None when the reply is not understood."""
    word = text.strip().lower()
    if word in TRUE_WORDS:
        return True
    if word in FALSE_WORDS:
        return False
    if word in QUIT_WORDS:
        return QUIT
    return None


def score_by_area(bank: Bank, results: list[Result]) -> list[dict[str, Any]]:
    """Right and total per area, in bank order, for areas that were asked."""
    rows = []
    for area in bank.areas:
        asked = [r for r in results if r.statement.area == area.id]
        if asked:
            rows.append(
                {
                    "id": area.id,
                    "title": area.title,
                    "right": sum(1 for r in asked if r.correct),
                    "total": len(asked),
                }
            )
    return rows


def next_pages(results: list[Result], limit: int = NEXT_PAGES) -> list[tuple[str, int]]:
    """Pages behind the most misses, most missed first, then first missed first."""
    misses = [r.statement.link for r in results if not r.correct]
    counts = Counter(misses)
    order = {link: misses.index(link) for link in counts}
    ranked = sorted(counts, key=lambda link: (-counts[link], order[link]))
    return [(link, counts[link]) for link in ranked[:limit]]


def _percent(part: int, whole: int) -> str:
    return f"{round(100 * part / whole)}%" if whole else "0%"


# ------------------------------------------------------------- interactive


def _wrap(text: str, indent: str = "  ") -> str:
    return textwrap.fill(text, width=WIDTH, initial_indent=indent, subsequent_indent=indent)


def run_quiz(
    bank: Bank,
    statements: list[Statement],
    ask: Callable[[str], str] = input,
    out: TextIO | None = None,
) -> list[Result]:
    """Ask each statement in turn. Stops on q, end of input or Ctrl-C."""
    out = out or sys.stdout
    titles = {a.id: a.title for a in bank.areas}
    results: list[Result] = []
    total = len(statements)
    print(
        f"\n{total} statement{'s' if total != 1 else ''}. Answer t or f; q stops early.\n",
        file=out,
    )
    for n, s in enumerate(statements, start=1):
        print(f"[{n}/{total}] {titles[s.area]}, {LEVEL_LABEL[s.level]}", file=out)
        print(_wrap(s.text), file=out)
        reply: bool | str | None = None
        while reply is None:
            try:
                raw = ask("True or false? [t/f, q to quit] ")
            except (EOFError, KeyboardInterrupt):
                print(file=out)
                reply = QUIT
                break
            reply = parse_reply(raw)
            if reply is None:
                print("  Please type t or f (or q to quit).", file=out)
        if reply == QUIT:
            print("\nStopping here.", file=out)
            break
        result = Result(s, bool(reply))
        results.append(result)
        verdict = "Right." if result.correct else "Not quite."
        truth = "true" if s.answer else "false"
        right = sum(1 for r in results if r.correct)
        print(f"  {verdict} It is {truth}.", file=out)
        print(_wrap(s.explanation), file=out)
        print(f"  Read: {s.link}", file=out)
        print(f"  Score: {right} of {len(results)}\n", file=out)
    return results


def _echoing(read: Callable[[str], str]) -> Callable[[str], str]:
    """Show piped answers after the prompt, so a transcript reads like a session."""

    def ask(prompt: str) -> str:
        reply = read(prompt)
        print(reply)
        return reply

    return ask


def render_summary(bank: Bank, results: list[Result]) -> str:
    if not results:
        return "No answers recorded. Run the quiz again when you have five minutes.\n"
    right = sum(1 for r in results if r.correct)
    rows = score_by_area(bank, results)
    width = max(len(r["title"]) for r in rows)
    out = [
        f"Final score: {right} of {len(results)} ({_percent(right, len(results))})",
        "",
        "By area:",
    ]
    for r in rows:
        out.append(f"  {r['title']:<{width}}  {r['right']} of {r['total']}")
    pages = next_pages(results)
    out.append("")
    if pages:
        out.append("Read next:")
        for i, (link, missed) in enumerate(pages, start=1):
            out.append(f"  {i}. {link} ({missed} missed)")
    else:
        out.append("No misses. Try another area, or --level assured for harder statements.")
    return "\n".join(out) + "\n"


def render_list(bank: Bank) -> str:
    width = max(len(a.id) for a in bank.areas)
    out = ["Areas (use the id with --area):", ""]
    for a in bank.areas:
        n = len(bank.in_area(a.id))
        out.append(f"  {a.id:<{width}}  {n:>3} statements  {a.title}")
    out += ["", f"Levels (use with --level): {', '.join(LEVELS)}.", f"Total: {len(bank.statements)} statements."]
    return "\n".join(out) + "\n"


# ------------------------------------------------------------------ export


def _escape(text: str) -> str:
    """Stop Markdown from reading a statement as HTML."""
    return text.replace("<", "&lt;").replace(">", "&gt;")


def render_area_page(bank: Bank, area: Area) -> str:
    items = bank.in_area(area.id)
    levels = Counter(s.level for s in items)
    mix = ", ".join(f"{LEVEL_LABEL[lv]} {levels[lv]}" for lv in LEVELS if levels[lv])
    out = [
        MARKER,
        "",
        f"# True or false: {area.title}",
        "",
        area.intro,
        "",
        f"{len(items)} statements ({mix}). Decide whether each one is true or false "
        "before you open the answer. Every answer says why and links to the page that teaches it.",
        "",
        f"Prefer the terminal? From the repository root, run `python3 exercises/quiz.py --area {area.id}`.",
        "",
    ]
    for n, s in enumerate(items, start=1):
        truth = "True" if s.answer else "False"
        out += [
            f"### {n}. {_escape(s.text)}",
            "",
            f"Level: {LEVEL_LABEL[s.level]}",
            "",
            "<details><summary>Answer</summary>",
            "",
            f"**{truth}.** {_escape(s.explanation)}",
            "",
            f"Read more: [{s.link}](../../{s.link})",
            "",
            "</details>",
            "",
        ]
    out += [
        "---",
        "",
        "[All true-or-false areas](README.md) · [Exercises](../README.md)",
    ]
    return "\n".join(out) + "\n"


def render_index(bank: Bank) -> str:
    out = [
        MARKER,
        "",
        "# True or false",
        "",
        f"{len(bank.statements)} statements about the playbook, in {len(bank.areas)} areas. "
        "Some are myths that sound right; others are facts that sound wrong. "
        "Each answer explains why in a few sentences and links to the page that teaches the practice.",
        "",
        "Play on GitHub by opening an area below, or in a terminal from the repository root:",
        "",
        "```bash",
        "python3 exercises/quiz.py                       # 10 random statements",
        "python3 exercises/quiz.py --area security ai    # only these areas",
        "python3 exercises/quiz.py --level foundation    # only one level",
        "python3 exercises/quiz.py --count 0 --seed 7    # every statement, repeatable order",
        "```",
        "",
        "The terminal quiz keeps a running score, shows your result by area and suggests three pages to read next.",
        "",
        "| Area | Statements | What it covers |",
        "|---|---|---|",
    ]
    for a in bank.areas:
        out.append(f"| [{a.title}]({a.id}.md) | {len(bank.in_area(a.id))} | {a.intro} |")
    out += [
        "",
        "To add or change a statement, edit [questions.toml](questions.toml), then run "
        "`python3 exercises/quiz.py --export` and `python3 exercises/quiz.py --check`.",
    ]
    return "\n".join(out) + "\n"


def expected_pages(bank: Bank) -> dict[str, str]:
    pages = {INDEX_NAME: render_index(bank)}
    for area in bank.areas:
        pages[f"{area.id}.md"] = render_area_page(bank, area)
    return pages


def export(bank: Bank, out_dir: Path) -> list[Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for name, text in expected_pages(bank).items():
        path = out_dir / name
        path.write_text(text, encoding="utf-8")
        written.append(path)
    return written


def _show(path: Path) -> str:
    try:
        return str(path.resolve().relative_to(Path.cwd().resolve()))
    except ValueError:
        return str(path)


def check(bank: Bank, repo: Path, export_dir: Path) -> list[str]:
    """Problems with links and exported pages. An empty list means all good."""
    problems: list[str] = []
    for s in bank.statements:
        if not (repo / s.link).is_file():
            problems.append(f"{s.id}: link {s.link} does not exist")
    expected = expected_pages(bank)
    for name, text in expected.items():
        path = export_dir / name
        if not path.is_file():
            problems.append(f"{_show(path)}: missing; run --export")
        elif path.read_text(encoding="utf-8") != text:
            problems.append(f"{_show(path)}: out of date; run --export")
    if export_dir.is_dir():
        for path in sorted(export_dir.glob("*.md")):
            if path.name in expected:
                continue
            if MARKER in path.read_text(encoding="utf-8").splitlines()[:1]:
                problems.append(f"{_show(path)}: generated page for an area that no longer exists; delete it")
    return problems


# ---------------------------------------------------------------------- cli


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    p.add_argument("--bank", type=Path, default=DEFAULT_BANK, help="question bank (TOML)")
    p.add_argument("--area", nargs="+", action="extend", metavar="AREA", help="only these areas")
    p.add_argument("--level", choices=LEVELS, help="only this level")
    p.add_argument(
        "--count", type=int, default=DEFAULT_COUNT,
        help=f"how many statements to ask (default {DEFAULT_COUNT}; 0 asks all)",
    )
    p.add_argument("--seed", type=int, help="fix the order, to repeat a session")
    p.add_argument("--list", action="store_true", help="list the areas and exit")
    p.add_argument(
        "--export", type=Path, nargs="?", const=DEFAULT_EXPORT, metavar="DIR",
        help="write one Markdown page per area (default: exercises/true-or-false)",
    )
    p.add_argument(
        "--check", action="store_true",
        help="validate the bank, its links and the exported pages; exit 1 on problems",
    )
    return p


def main(argv: list[str] | None = None, ask: Callable[[str], str] = input) -> int:
    args = build_parser().parse_args(argv)
    try:
        bank = load_bank(args.bank)
        if args.check:
            problems = check(bank, REPO, args.export or DEFAULT_EXPORT)
            for problem in problems:
                print(problem, file=sys.stderr)
            if problems:
                print(f"\n{len(problems)} problem(s).", file=sys.stderr)
                return 1
            print(f"OK: {len(bank.statements)} statements in {len(bank.areas)} areas; pages up to date.")
            return 0
        if args.export:
            for path in export(bank, args.export):
                print(f"Wrote {_show(path)}", file=sys.stderr)
            return 0
        if args.list:
            sys.stdout.write(render_list(bank))
            return 0
        statements = select(bank, args.area, args.level, args.count, args.seed)
    except QuizError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    if ask is input and not sys.stdin.isatty():
        ask = _echoing(input)
    results = run_quiz(bank, statements, ask=ask)
    sys.stdout.write("\n" + render_summary(bank, results))
    return 0


if __name__ == "__main__":
    sys.exit(main())
